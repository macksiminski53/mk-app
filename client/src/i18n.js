export function getTranslator(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  const fallback = STRINGS.en;
  return function t(key, ...args) {
    const entry = table[key] ?? fallback[key];
    if (typeof entry === 'function') return entry(...args);
    return entry ?? key;
  };
}
